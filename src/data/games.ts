/** Builds the full preset for a tuned game from its genre layout. */
export function gamePreset(spec: GameSpec): Preset {
  const base = archetypePreset(spec.base);
  const claimed = new Set(Object.values(spec.bindings).flat());
  const bindings: Bindings = {};

  // Keep base bindings the game does not override, minus keys the game uses elsewhere.
  for (const [target, codes] of Object.entries(base.bindings) as [Target, string[]][]) {
    if (spec.bindings[target] || spec.unbind?.includes(target)) continue;
    const kept = codes.filter((code) => !claimed.has(code));
    if (kept.length) bindings[target] = kept;
  }
  for (const [target, codes] of Object.entries(spec.bindings) as [Target, string[]][]) {
    bindings[target] = [...codes];
  }

  return {
    id: `game:${spec.slug}${spec.variant ? `:${spec.variant}` : ''}`,
    name: spec.variant ? `${spec.name} (${spec.variant})` : spec.name,
    archetype: spec.base,
    bindings,
    labels: { ...spec.labels },
    toggles: spec.toggles ? [...spec.toggles] : [],
    mouse: { ...base.mouse, ...spec.mouse },
    analog: { ...base.analog, ...spec.analog },
    ...(spec.notes ? { notes: spec.notes } : {}),
  };
}
