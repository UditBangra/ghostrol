// Tuned presets for individual games.
//
// Each one starts from a genre layout and maps every controller button the game uses to
// the key a PC player of that game would expect, with the game's own name for the action.
// Sources for each layout are listed in docs/PRESETS.md. Only add a game here when its
// default controller layout is confirmed by at least one reliable source.

import type {
  AnalogSettings,
  ArchetypeId,
  Bindings,
  Labels,
  MouseSettings,
  Preset,
} from '../core/preset';
import type { Button, Target } from '../core/targets';
import { archetypePreset } from './archetypes';

export interface GameSpec {
  /** Stable id, used in preset ids. Never change it once released. */
  slug: string;
  name: string;
  /** Store titles this preset applies to. Matched after normalization, editions included. */
  titles: string[];
  base: ArchetypeId;
  bindings: Bindings;
  labels: Labels;
  /** Targets from the base layout that this game does not use. */
  unbind?: Target[];
  toggles?: Button[];
  mouse?: Partial<MouseSettings>;
  analog?: Partial<AnalogSettings>;
  notes?: string;
  /** Extra presets for the same game, such as a second role. */
  variant?: string;
  /**
   * The game is not on Xbox Cloud Gaming, so it is played through Remote Play from the
   * user's own console, where the preset is picked by hand. Exempt from the catalog check.
   */
  consoleOnly?: boolean;
}

