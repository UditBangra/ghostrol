export const ARCHETYPE_IDS = Object.keys(SPECS) as ArchetypeId[];

export function archetypeName(id: ArchetypeId): string {
  return SPECS[id].name;
}

export function archetypeSummary(id: ArchetypeId): string {
  return SPECS[id].summary;
}

/** The built-in preset for a genre layout. */
export function archetypePreset(id: ArchetypeId): Preset {
  const spec = SPECS[id];
  return {
    id: `layout:${id}`,
    name: `${spec.name} layout`,
    archetype: id,
    bindings: structuredClone(spec.bindings),
    labels: { ...spec.labels },
    toggles: [],
    mouse: { ...DEFAULT_MOUSE, ...spec.mouse },
    analog: { ...DEFAULT_ANALOG, ...spec.analog },
  };
}

export const DEFAULT_ARCHETYPE: ArchetypeId = 'action';
